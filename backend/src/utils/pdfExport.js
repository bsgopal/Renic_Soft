import PDFDocument from 'pdfkit';

/**
 * Builds a tabular A4 PDF report buffer for a listing.
 * @param {Object} opts
 * @param {string} opts.companyName
 * @param {string} opts.title
 * @param {string} opts.subtitle
 * @param {string[]} opts.headers
 * @param {Array<Array<string|number>>} opts.rows
 * @param {string[]} [opts.rightAligned] header names to align right
 * @param {Array<{label:string,value:string}>} [opts.summary]
 */
export async function buildReportBuffer({ companyName, title, subtitle, headers, rows, rightAligned = [], summary = [] }) {
  const doc = new PDFDocument({ size: 'A4', layout: 'portrait', margin: 36, bufferPages: true });
  const chunks = [];
  doc.on('data', (c) => chunks.push(c));

  const pageWidth = doc.page.width - 72;
  const colWidths = headers.map(() => pageWidth / headers.length);
  const rightSet = new Set(rightAligned);

  const money = (n) => 'Rs. ' + (Number(n) || 0).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 });

  const drawHeaderRow = () => {
    doc.fillColor('#f1f3f4').rect(36, doc.y, pageWidth, 22).fill();
    let x = 36;
    headers.forEach((h, i) => {
      doc.fillColor('#5f6368').font('Helvetica-Bold').fontSize(8.5)
        .text(String(h), x + 6, doc.y + 7, { width: colWidths[i] - 12, align: rightSet.has(h) ? 'right' : 'left' });
      x += colWidths[i];
    });
    doc.moveDown(0.7);
  };

  const ensureSpace = () => {
    if (doc.y > doc.page.height - 90) {
      doc.addPage();
      drawHeaderRow();
    }
  };

  // ---- Title header ----
  doc.fillColor('#1a73e8').rect(36, 24, 60, 10).fill();
  doc.fillColor('#202124').fontSize(16).font('Helvetica-Bold')
    .text(companyName || 'Report', 36, 22);
  doc.fontSize(9).font('Helvetica').fillColor('#5f6368')
    .text(subtitle || '', 36, 44, { width: pageWidth, align: 'right' });
  doc.moveDown(1.9);

  doc.fillColor('#1a73e8').fontSize(18).font('Helvetica-Bold').text(title, { align: 'center' });
  doc.fontSize(9).font('Helvetica').fillColor('#5f6368')
    .text(`Generated on: ${new Date().toLocaleString('en-IN')}`, { align: 'center' });
  doc.moveDown(1);
  doc.moveTo(36, doc.y).lineTo(36 + pageWidth, doc.y).strokeColor('#e8eaed').lineWidth(1).stroke();
  doc.moveDown(1);

  // ---- Table ----
  drawHeaderRow();
  rows.forEach((r, ri) => {
    ensureSpace();
    if (ri % 2 === 1) doc.fillColor('#f8f9fa').rect(36, doc.y - 1, pageWidth, 17).fill();
    let x = 36;
    headers.forEach((h, i) => {
      const val = r[i];
      const cellText = String(val === undefined || val === null ? '' : val);
      doc.fillColor('#202124').font('Helvetica').fontSize(8.5)
        .text(cellText, x + 6, doc.y, { width: colWidths[i] - 12, align: rightSet.has(h) ? 'right' : 'left' });
      x += colWidths[i];
    });
    doc.moveDown(0.42);
  });

  if (summary.length) {
    doc.moveDown(0.8);
    doc.moveTo(36, doc.y).lineTo(36 + pageWidth, doc.y).strokeColor('#dadce0').lineWidth(0.8).stroke();
    doc.moveDown(0.6);
    summary.forEach((row) => {
      ensureSpace();
      const y = doc.y;
      doc.font('Helvetica').fontSize(9.5).fillColor('#5f6368').text(row.label, 36 + pageWidth / 2 - 130, y, { width: 130, align: 'left' });
      doc.font('Helvetica-Bold').fillColor('#202124').text(row.value, 36 + pageWidth / 2 + 10, y, { width: pageWidth / 2 - 50, align: 'right' });
      doc.moveDown(0.55);
    });
  }

  // ---- Footer on every page ----
  const pages = doc.bufferedPageRange();
  for (let i = pages.start; i < pages.start + pages.count; i++) {
    doc.switchToPage(i);
    const footerY = doc.page.height - 30;
    doc.save();
    doc.font('Helvetica').fontSize(8).fillColor('#9aa0a6')
      .text(`Generated by ${companyName || 'Renic Soft'}  |  Page ${i + 1} of ${pages.count}`, 36, footerY, { width: pageWidth, align: 'center' });
    doc.restore();
  }

  return new Promise((resolve, reject) => {
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    doc.end();
  });
}

/**
 * Builds a professional single-document A4 PDF (quotation / invoice) matching
 * the reference print format exactly: letterhead, title box, meta, Quotation
 * To / Prepared By, Project/Subject, items table, totals with Advance/Deposit
 * and Balance Due, Payment Terms, Terms & Conditions, signature blocks.
 * All company details come from the caller — nothing is hardcoded here.
 * @param {Object} opts
 * @param {Object} opts.quote   - quotation OR invoice document
 * @param {{name:string,address?:string,phone?:string,email?:string,gst?:string}} [opts.company]
 * @param {string} [opts.title]   - big document title, e.g. "Renic Quotation" / "Renic Invoice"
 * @param {string} [opts.metaNo]  - label of the document number column
 * @param {string} [opts.footer]  - brand name shown in the footer
 * @param {{method?:string,amountPaid?:number,balanceDue?:number}} [opts.payment] - invoice payment block
 */
export async function buildQuotationBuffer({ quote, company = null, title = 'Renic Quotation', metaNo = 'Quotation No', footer = '', payment = null, paymentDetails = '', termsConditions = '' }) {
  const doc = new PDFDocument({ size: 'A4', margin: 40, bufferPages: true });
  const chunks = [];
  doc.on('data', (c) => chunks.push(c));

  const pageWidth = doc.page.width - 80;
  const pageHeight = doc.page.height;

  const money = (n) => 'Rs. ' + (Number(n) || 0).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  const fmt = (d) => (d ? new Date(d).toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' }) : '-');

  const cname = (company && company.name) || '';
  const caddr = (company && company.address) || '';
  const cphone = (company && company.phone) || '';
  const cemail = (company && company.email) || '';
  const cgst = (company && company.gst) || '';

  const isInvoice = !!payment;
  const balance = (quote.grandTotal || 0) - (quote.advanceDeposit || 0);
  const totalLabel = isInvoice ? 'TOTAL' : 'TOTAL';

  // ================= Letterhead (centered, double rule) =================
  doc.moveTo(40, 42).lineTo(40 + pageWidth, 42).lineWidth(1.5).strokeColor('#1a73e8').stroke();
  doc.moveTo(40, 45).lineTo(40 + pageWidth, 45).lineWidth(0.8).stroke();

  doc.fillColor('#202124').font('Helvetica-Bold').fontSize(16).text(cname || title, 40, 52, { width: pageWidth, align: 'center' });
  doc.fillColor('#5f6368').font('Helvetica').fontSize(8.5).text(caddr, 40, 70, { width: pageWidth, align: 'center' });
  const contactLine = ['Phone: ' + (cphone || '—'), 'Email: ' + (cemail || '—')].join('   |   ');
  doc.text(contactLine, 40, 82, { width: pageWidth, align: 'center' });
  if (cgst) doc.text('GSTIN/Tax ID: ' + cgst, 40, 94, { width: pageWidth, align: 'center' });
  const headBottom = cgst ? 104 : 96;
  doc.moveTo(40, headBottom).lineTo(40 + pageWidth, headBottom).lineWidth(1.5).strokeColor('#1a73e8').stroke();
  doc.moveTo(40, headBottom + 3).lineTo(40 + pageWidth, headBottom + 3).lineWidth(0.8).stroke();
  doc.y = headBottom + 14;

  // ================= Title box + meta =================
  const titleBoxY = doc.y;
  doc.save().roundedRect(40, titleBoxY, 170, 30, 4).lineWidth(1.2).stroke('#9aa0a6');
  doc.restore();
  doc.fillColor('#202124').font('Helvetica-Bold').fontSize(15).text(title, 40, titleBoxY + 8, { width: 170, align: 'center' });

  const meta = [
    [metaNo, quote.quoteNumber || quote.invoiceNumber],
    ['Date', fmt(quote.quoteDate || quote.invoiceDate)],
    ...(isInvoice
      ? [['Payment Status', quote.status || (Number(quote.balanceDue) > 0 ? 'Partially Paid' : 'Paid')]]
      : [['Valid Until', quote.validUntil ? fmt(quote.validUntil) : '-']]),
    ['Status', quote.status || 'draft']
  ];
  const metaX = 40 + pageWidth - 240;
  const metaW = 240;
  let my = titleBoxY - 2;
  meta.forEach(([label, val]) => {
    doc.font('Helvetica').fontSize(7.5).fillColor('#5f6368').text(label.toUpperCase(), metaX, my, { width: metaW, align: 'right' });
    doc.font('Helvetica-Bold').fontSize(9.5).fillColor('#202124').text(String(val || '-'), metaX, my + 9, { width: metaW, align: 'right' });
    my += 21;
  });
  doc.y = Math.max(titleBoxY + 34, my);

  // ================= Quotation To / Prepared By =================
  const toY = doc.y;
  doc.font('Helvetica-Bold').fontSize(8).fillColor('#1a73e8').text('QUOTATION TO', 40, toY);
  doc.font('Helvetica-Bold').fontSize(10).fillColor('#202124').text(quote.customerName || 'Walk-in Customer', 40, toY + 11);
  const cusLines = [
    quote.customerAddress,
    quote.customerPhone,
    quote.customerEmail,
    quote.customerGSTIN ? 'GSTIN: ' + quote.customerGSTIN : ''
  ].filter(Boolean);
  let ly = toY + 22;
  cusLines.forEach((l) => {
    doc.font('Helvetica').fontSize(8).fillColor('#5f6368').text(l, 40, ly, { width: 250 });
    ly += 11;
  });

  doc.font('Helvetica-Bold').fontSize(8).fillColor('#1a73e8').text('PREPARED BY', 40 + pageWidth - 250, toY, { width: 250, align: 'right' });
  doc.font('Helvetica-Bold').fontSize(10).fillColor('#202124').text('Sales Representative', 40 + pageWidth - 250, toY + 11, { width: 250, align: 'right' });
  doc.font('Helvetica').fontSize(8).fillColor('#5f6368')
    .text('Sales Team', 40 + pageWidth - 250, toY + 22, { width: 250, align: 'right' })
    .text(cemail || '—', 40 + pageWidth - 250, toY + 33, { width: 250, align: 'right' });
  doc.y = Math.max(ly, toY + 46) + 6;

  // ================= Project / Subject =================
  doc.font('Helvetica-Bold').fontSize(8).fillColor('#1a73e8').text('PROJECT / SUBJECT', 40, doc.y);
  doc.moveDown(0.2);
  doc.font('Helvetica').fontSize(8.5).fillColor('#202124').text('Quotation for goods & services as detailed below', 40, doc.y);
  if (quote.notes) {
    doc.moveDown(0.15);
    doc.font('Helvetica').fontSize(8).fillColor('#80868b').text('Refer: ' + quote.notes, 40, doc.y, { width: pageWidth });
    doc.moveDown(0.2);
  } else {
    doc.moveDown(0.5);
  }

  // ================= Items table =================
  const headers = ['S.No', 'Item Description', 'Qty', 'Unit', 'Unit Price', 'Amount'];
  const colWidths = [26, pageWidth - 26 - 36 - 36 - 86 - 92, 36, 36, 86, 92];
  const startX = 40;

  const drawTableHeader = () => {
    const top = doc.y;
    doc.fillColor('#1a73e8').rect(startX, top, pageWidth, 20).fill();
    let x = startX;
    headers.forEach((h, i) => {
      doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(7.5)
        .text(h, x + 4, top + 6, { width: colWidths[i] - 8, align: ['S.No', 'Qty', 'Unit'].includes(h) ? 'center' : 'right' });
      x += colWidths[i];
    });
    doc.y = top + 24;
  };

  const ensureSpace = (extra = 0) => {
    if (doc.y + extra > pageHeight - 180) {
      doc.addPage();
      drawTableHeader();
    }
  };

  const gross = (it) => (Number(it.qty) || 0) * (Number(it.rate) || 0);

  drawTableHeader();
  (quote.items || []).forEach((it, idx) => {
    const descH = it.description ? doc.heightOfString(it.description, { width: colWidths[1] - 10 }) : 0;
    const hsnH = it.hsnCode ? doc.heightOfString('HSN: ' + it.hsnCode, { width: colWidths[1] - 10 }) : 0;
    const rowH = Math.max(24, 18 + descH + hsnH + 4);
    ensureSpace(rowH + 10);
    const rowTop = doc.y;
    if (idx % 2 === 1) doc.fillColor('#f8f9fa').rect(startX, rowTop, pageWidth, rowH).fill();
    const midY = rowTop + rowH / 2 - 4;

    doc.font('Helvetica').fontSize(8).fillColor('#9aa0a6')
      .text(String(idx + 1), startX + 4, midY, { width: colWidths[0] - 8, align: 'center' });

    doc.font('Helvetica-Bold').fontSize(8.5).fillColor('#202124')
      .text(it.name || '', startX + colWidths[0] + 2, rowTop + 3, { width: colWidths[1] - 10 });
    if (it.description) {
      doc.font('Helvetica').fontSize(7).fillColor('#80868b')
        .text(it.description, startX + colWidths[0] + 2, rowTop + 13, { width: colWidths[1] - 10 });
    }
    if (it.hsnCode) {
      doc.font('Helvetica').fontSize(6.5).fillColor('#9aa0a6')
        .text('HSN: ' + it.hsnCode, startX + colWidths[0] + 2, rowTop + 13 + descH, { width: colWidths[1] - 10 });
    }

    let x = startX + colWidths[0] + colWidths[1];
    const numCols = colWidths.slice(2);
    const vals = [it.qty === '' || it.qty === null || it.qty === undefined ? '' : String(it.qty), it.unit || 'Nos', money(it.rate), money(gross(it))];
    vals.forEach((v, i) => {
      doc.font(i === 3 ? 'Helvetica-Bold' : 'Helvetica').fontSize(i === 3 ? 8.5 : 8).fillColor('#202124')
        .text(String(v), x + 4, midY, { width: numCols[i] - 8, align: i === 1 ? 'center' : 'right' });
      x += numCols[i];
    });
    doc.y = rowTop + rowH + 4;
  });

  doc.moveDown(0.9);

  // ================= Totals panel (right) =================
  const panelX = startX + pageWidth - 240;
  const panelW = 240;
  let py = doc.y;
  const row = (label, value, h = 20, fill = null, labelColor = '#202124', valueColor = '#202124', font = 'Helvetica') => {
    if (fill) {
      doc.save();
      if (fill.bg) doc.fillColor(fill.bg).rect(panelX, py, panelW, h).fill();
      if (fill.border) { doc.lineWidth(0.8).strokeColor(fill.border).rect(panelX, py, panelW, h).stroke(); }
      doc.restore();
    }
    doc.font(font).fontSize(9).fillColor(labelColor).text(label, panelX + 8, py + h / 2 - 5, { width: panelW / 2, align: 'left' });
    doc.font(font).fontSize(9).fillColor(valueColor).text(value, panelX + panelW / 2, py + h / 2 - 5, { width: panelW / 2 - 8, align: 'right' });
    py += h;
  };

  row('Subtotal', money(quote.subTotal));
  row('Discount', '- ' + money(quote.discountTotal));
  row('Tax (GST/VAT %)', '+ ' + money(quote.taxTotal));
  row('TOTAL', money(quote.grandTotal), 26, { bg: '#202124' }, '#ffffff', '#ffffff', 'Helvetica-Bold');
  row('Advance / Deposit Required', money(quote.advanceDeposit || 0));
  row('Balance Due', money(balance), 26, { bg: '#fdf3e3', border: '#f2c66d' }, '#b45309', '#b45309', 'Helvetica-Bold');
  doc.y = py + 8;

  // ================= Payment block (invoice only) =================
  if (payment) {
    const payY = doc.y;
    const payH = 52;
    doc.fillColor('#eef4ff').rect(40, payY, pageWidth, payH).fill();
    doc.fillColor('#1a73e8').font('Helvetica-Bold').fontSize(8).text('PAYMENT DETAILS', 50, payY + 6);
    const paid = Number(payment.amountPaid) || 0;
    const bal = Number(payment.balanceDue) || 0;
    const leftW = pageWidth - 170;
    doc.font('Helvetica').fontSize(8.5).fillColor('#202124')
      .text('Method: ' + (payment.method || '-'), 50, payY + 16, { width: leftW })
      .text('Amount Paid: ' + money(paid), 50, payY + 27, { width: leftW });
    const rightX = 50 + leftW + 10;
    const rightW = pageWidth - leftW - 60;
    doc.font('Helvetica').fontSize(8).fillColor('#5f6368').text('BALANCE DUE', rightX, payY + 10, { width: rightW, align: 'right' });
    doc.font('Helvetica-Bold').fontSize(11).fillColor(bal > 0 ? '#d93025' : '#188038')
      .text(money(bal), rightX, payY + 19, { width: rightW, align: 'right' });
    doc.font('Helvetica-Bold').fontSize(8).fillColor(bal > 0 ? '#d93025' : '#188038')
      .text(bal > 0 ? 'PARTIALLY PAID' : 'FULLY PAID', rightX, payY + 37, { width: rightW, align: 'right' });
    doc.y = payY + payH + 8;
  }

  // ================= Payment Terms / Details =================
  const paymentHeading = isInvoice ? 'PAYMENT DETAILS' : 'PAYMENT TERMS';
  doc.font('Helvetica-Bold').fontSize(8).fillColor('#1a73e8').text(paymentHeading, 40, doc.y);
  doc.moveDown(0.2);
  const settingsPayment = (paymentDetails || '').split('\n').map((s) => s.trim()).filter(Boolean);
  const defaultPayment = isInvoice
    ? [
        'Advance received as per the payment details above.',
        'Balance due as per the due date above.',
        'Accepted payment modes: Bank Transfer / UPI / Cheque / Card.',
        'Please reference the Invoice No. when making payment.'
      ]
    : [
        'Advance payment of 50% is required to confirm and begin the order.',
        'Balance amount to be paid upon delivery / completion.',
        'Accepted payment modes: Bank Transfer / UPI / Cheque / Card.'
      ];
  const paymentItems = settingsPayment.length ? settingsPayment : defaultPayment;
  let pty = doc.y;
  paymentItems.forEach((t) => {
    doc.font('Helvetica').fontSize(8.5).fillColor('#202124').text('•   ' + t, 40, pty, { width: pageWidth });
    pty += 12;
  });
  doc.y = pty + 8;

  // ================= Terms & Conditions =================
  doc.font('Helvetica-Bold').fontSize(8).fillColor('#1a73e8').text('TERMS & CONDITIONS', 40, doc.y);
  doc.moveDown(0.2);
  const settingsTerms = (termsConditions || '').split('\n').map((s) => s.trim()).filter(Boolean);
  const quoteTerms = (quote.terms || '').split('\n').map((s) => s.trim()).filter(Boolean);
  const defaultTerms = isInvoice
    ? [
        'This invoice is payable in full unless a payment plan has been agreed in writing.',
        'Please verify all details and report any discrepancy within 7 days of receipt.',
        'This is a computer-generated invoice and does not require a physical signature.'
      ]
    : [
        'This quotation is valid for 14 days from the date of issue unless stated otherwise.',
        'Prices are subject to change without prior notice after the validity period.',
        'Taxes shown are as applicable on the date of this quotation.'
      ];
  const termItems = settingsTerms.length ? settingsTerms : (quoteTerms.length ? quoteTerms : defaultTerms);
  let tty = doc.y;
  termItems.forEach((t) => {
    doc.font('Helvetica').fontSize(8.5).fillColor('#202124').text('•   ' + t, 40, tty, { width: pageWidth });
    tty += 12;
  });
  doc.y = tty + 8;

  // ================= Signature blocks =================
  const sigY = pageHeight - 96;
  if (doc.y > sigY) {
    doc.addPage();
    const newSigY = doc.page.height - 96;
    doc.y = newSigY - 20;
  }
  const sY = Math.min(sigY, pageHeight - 96);
  doc.font('Helvetica-Bold').fontSize(7.5).fillColor('#5f6368')
    .text('AUTHORIZED SIGNATURE', 40, sY - 46, { width: pageWidth / 2 - 20, align: 'left' })
    .text('CUSTOMER ACCEPTANCE & SIGNATURE', 40 + pageWidth / 2, sY - 46, { width: pageWidth / 2 - 20, align: 'right' });
  doc.moveTo(40, sY).lineTo(40 + pageWidth / 2 - 40, sY).strokeColor('#dadce0').lineWidth(0.8).stroke();
  doc.moveTo(40 + pageWidth / 2 + 20, sY).lineTo(40 + pageWidth, sY).stroke();
  doc.font('Helvetica').fontSize(8.5).fillColor('#202124')
    .text('For ' + (cname || title), 40, sY + 4, { width: pageWidth / 2 - 20, align: 'left' })
    .text('Customer Signature', 40 + pageWidth / 2, sY + 4, { width: pageWidth / 2 - 20, align: 'right' });

  // Thank-you line
  doc.font('Helvetica-Oblique').fontSize(8.5).fillColor('#9aa0a6')
    .text('Thank you for considering ' + (cname || title) + '. We look forward to working with you.', 40, sY + 24, { width: pageWidth, align: 'center' });

  // ================= Footer on every page =================
  const pages = doc.bufferedPageRange();
  for (let i = pages.start; i < pages.start + pages.count; i++) {
    doc.switchToPage(i);
    const footerY = doc.page.height - 30;
    const footerText = [footer, 'Page ' + String(i + 1) + ' of ' + String(pages.count)].filter(Boolean).join('  |  ');
    doc.font('Helvetica').fontSize(7.5).fillColor('#9aa0a6')
      .text(footerText, 40, footerY, { width: pageWidth, align: 'center' });
  }

  return new Promise((resolve, reject) => {
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    doc.end();
  });
}
